const merge = (
  items: Array<Partial<KanjiChar>>,
  defaultJlpt: 'N5' | 'N4' | 'N3' | 'N2',
): KanjiChar[] =>
  items.map((k) => {
    const strokes = k.strokes ?? 0;
    // Генерируем strokeOrder из количества штрихов, если его нет.
    // Это позволяет показывать список штрихов в модалке для всех кандзи.
    const strokeOrder =
      k.strokeOrder ?? (strokes > 0
        ? Array.from({ length: strokes }, (_, i) => `${i + 1}. Штрих (см. анимацию выше)`)
        : []);
    return {
      char: k.char ?? '?',
      meaning: k.meaning ?? '—',
      onyomi: k.onyomi ?? [],
      kunyomi: k.kunyomi ?? [],
      strokes,
      jlpt: k.jlpt ?? defaultJlpt,
      examples: k.examples ?? [],
      strokeOrder,
      radicals: k.radicals ?? '',
    };
  });

